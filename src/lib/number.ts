/**
 * Парсить рядок із числового `<input>` у число, приймаючи КОМУ як
 * десятковий роздільник нарівні з крапкою.
 *
 * Чому це потрібно: `<input type="number">` за специфікацією повинен
 * приймати лише крапку, але мобільна цифрова клавіатура з RU/UK-
 * розкладкою (саме такою користується весь застосунок — усі скріни в
 * цьому проєкті українською/російською) підставляє кому на місці
 * десяткового роздільника, і принаймні на iOS Safari браузер це НЕ
 * фільтрує — `input.value` реально повертає рядок з комою всупереч
 * специфікації. Голий `Number("0,01")` дає `NaN`; якщо цей NaN якимось
 * шляхом (напр. обхідний код, не через типову перевірку canSubmit)
 * доходив до сервера як РЯДОК "0,01" замість числа — Postgres кидав
 * сиру `22P02 invalid input syntax for type numeric`, яку клієнт не
 * розпізнавав як відому помилку і ховав за нічого не значущим "Не
 * удалось выполнить действие" (живий кейс: створення завдання в
 * адмінці з нагородою "0,01").
 */
export function parseLocaleNumber(raw: string): number {
  return Number(raw.trim().replace(',', '.'))
}
